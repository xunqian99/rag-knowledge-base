package cn.ragserver.common;

/**
 * 降级原因。响应用它告诉调用方"到底是哪里降级了"。
 *
 * 【为什么不能只返回一个 true/false】
 *
 * 这个项目里的降级分两类,性质完全不同:
 *
 *   精排挂了  -> 答案仍然是正常的自然语言答案,只是排序退化了
 *   大模型挂了 -> 返回的是「检索到的原文清单」,**它根本不是答案**
 *
 * 两者用同一个布尔值表示的话,前端没法区分,只能一刀切 ——
 * 而它们本该是完全不同的展示方式。
 *
 * 所以响应里返回的是一个**降级清单**,每项带 code 和 message:
 *   code    给程序做分支判断(稳定标识,不要改)
 *   message 直接展示给人看
 *
 * 【为什么用枚举而不是散落的字符串】
 *
 * 调用方要按 code 写分支逻辑。如果 code 是拼出来的字符串,
 * 改一次文案就可能悄悄改掉 code,前端的分支会静默失效。
 */
public enum DegradationCode {

    /** 某一路召回通道失败(ES 或 pgvector),本次只用其余通道的结果 */
    RECALL_CHANNEL_DOWN,

    /** 重排序不可用,本次用的是 RRF 的排序结果 */
    RERANK_UNAVAILABLE,

    /** 大模型不可用,返回的是检索到的原文片段而不是答案 */
    CHAT_MODEL_UNAVAILABLE
}
