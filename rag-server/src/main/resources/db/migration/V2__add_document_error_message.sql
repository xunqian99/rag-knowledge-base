-- ============================================================
-- V2 · 给 document 表增加「失败原因」字段
--
-- 为什么需要它:第 6 项加了文本切分。切分可能失败(文件损坏、编码无法识别、
-- 内容为空等等)。失败时必须把原因记下来,否则运维只能看到一条 status=FAILED
-- 的记录,完全不知道发生了什么。
--
-- 【注意】这是「上线后改表结构」的示范:V1 已经在数据库里执行过了,
-- 绝不能回头去改 V1 的脚本,只能像这样新增一个 V2。
-- 这样任何环境(同事的电脑、测试、生产)执行顺序都一致。
-- ============================================================

ALTER TABLE document ADD COLUMN error_message TEXT;

-- 按状态查询是高频操作(例如第 23 项要捞出所有 FAILED 的文档重试),
-- 加个索引。注意:状态区分度不高、表数据量小时,索引收益有限,
-- 这里加是因为查询确实频繁,而且能避免全表扫描。
CREATE INDEX idx_document_status ON document (status);
